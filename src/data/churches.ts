export function townSlug(city: string): string {
  return city
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

export function churchGroups(list: Church[] = churches): ChurchGroup[] {
  const used = new Set<string>();
  const groups: ChurchGroup[] = [];
  for (const town of primaryTowns) {
    const townChurches = list
      .filter((church) => church.city === town)
      .sort((a, b) => a.name.localeCompare(b.name, 'en'));
    if (townChurches.length === 0) continue;
    used.add(town);
    groups.push({ id: townSlug(town), label: town, churches: townChurches });
  }
  const otherTowns = [...new Set(list.map((church) => church.city).filter((city) => !used.has(city)))].sort((a, b) =>
    a.localeCompare(b, 'en'),
  );
  const elsewhere = otherTowns.flatMap((town) =>
    list.filter((church) => church.city === town).sort((a, b) => a.name.localeCompare(b.name, 'en')),
  );
  if (elsewhere.length > 0) {
    groups.push({ id: 'elsewhere', label: 'Elsewhere in the county', churches: elsewhere });
  }
  return groups;
}

export function websiteLabel(url: string): string {
  try {
    const host = new URL(url).hostname.replace(/^www\./, '');
    if (host === 'facebook.com' || host.endsWith('.facebook.com')) return 'Facebook page';
    return host;
  } catch {
    return 'Church website';
  }
}

